#!/usr/bin/env python3
"""Convert the InkLike sleep logo to the renderer's 1-bit bitmap (requires Pillow)."""

from pathlib import Path

from PIL import Image, ImageOps


ROOT = Path(__file__).resolve().parent.parent
SIZE = 120


def main():
    with Image.open(ROOT / "assets/branding/InkBottleWhiteOutline.png") as source:
        # Keep source orientation, colors and transparency. Only resize and
        # quantize to the display's one-bit color and coverage planes.
        scaled = ImageOps.contain(source.convert("RGBA"), (SIZE, SIZE), Image.Resampling.LANCZOS)
        canvas = Image.new("RGBA", (SIZE, SIZE), (0, 0, 0, 0))
        canvas.paste(scaled, ((SIZE - scaled.width) // 2, (SIZE - scaled.height) // 2))
        bitmap = canvas.convert("L").convert("1", dither=Image.Dither.FLOYDSTEINBERG)
        coverage = canvas.getchannel("A").point(lambda value: 255 if value >= 128 else 0, mode="1")

    data = bitmap.tobytes()
    assert len(data) == SIZE * SIZE // 8
    def array(name, values):
        rows = ["    " + ", ".join(f"0x{value:02x}" for value in values[offset:offset + 15]) + ","
                for offset in range(0, len(values), 15)]
        return [f"static const uint8_t {name}[] = {{", *rows, "};"]

    header = "\n".join([
        "#pragma once",
        "#include <cstdint>",
        "",
        "// Generated by scripts/generate_sleep_logo.py; edit assets/branding/InkBottleWhiteOutline.png.",
        f"static constexpr int InkLikeSleepLogoSize = {SIZE};",
        *array("InkLikeSleepLogo", data),
        *array("InkLikeSleepLogoCoverage", coverage.tobytes()),
        "static_assert(sizeof(InkLikeSleepLogo) == InkLikeSleepLogoSize * InkLikeSleepLogoSize / 8);",
        "static_assert(sizeof(InkLikeSleepLogoCoverage) == sizeof(InkLikeSleepLogo));",
        "",
    ])
    (ROOT / "src/images/InkLikeSleepLogo.h").write_text(header, encoding="utf-8")


if __name__ == "__main__":
    main()
