#!/usr/bin/env python3
"""Convert the InkLike sleep logo to the renderer's 1-bit bitmap (requires Pillow)."""

from pathlib import Path

from PIL import Image, ImageOps


ROOT = Path(__file__).resolve().parent.parent
SIZE = 120


def main():
    with Image.open(ROOT / "assets/branding/InkBottleWhiteOutline.png") as source:
        # Preserve the white outline against black, then invert for the light
        # framebuffer. SleepActivity inverts it back for the dark sleep mode.
        rgba = source.convert("RGBA")
        background = Image.new("RGBA", rgba.size, (0, 0, 0, 255))
        background.alpha_composite(rgba)
        scaled = ImageOps.contain(background.convert("L"), (SIZE, SIZE), Image.Resampling.LANCZOS)
        canvas = Image.new("L", (SIZE, SIZE), 0)
        canvas.paste(scaled, ((SIZE - scaled.width) // 2, (SIZE - scaled.height) // 2))
        bitmap = ImageOps.invert(canvas).point(lambda value: 255 if value >= 128 else 0, mode="1")

    data = bitmap.tobytes()
    assert len(data) == SIZE * SIZE // 8
    rows = ["    " + ", ".join(f"0x{value:02x}" for value in data[offset:offset + 15]) + ","
            for offset in range(0, len(data), 15)]
    header = "\n".join([
        "#pragma once",
        "#include <cstdint>",
        "",
        "// Generated by scripts/generate_sleep_logo.py; edit assets/branding/InkBottleWhiteOutline.png.",
        f"static constexpr int InkLikeSleepLogoSize = {SIZE};",
        "static const uint8_t InkLikeSleepLogo[] = {",
        *rows,
        "};",
        "static_assert(sizeof(InkLikeSleepLogo) == InkLikeSleepLogoSize * InkLikeSleepLogoSize / 8);",
        "",
    ])
    (ROOT / "src/images/InkLikeSleepLogo.h").write_text(header, encoding="utf-8")


if __name__ == "__main__":
    main()
